#[tokio::test]
async fn logical_topics_and_examples_survive_source_moves() -> Result<()> {
    let source = tempfile::tempdir()?;
    setup(
        source.path(),
        "Intro.\n\n## Build\n\n```sh\ncargo build\n```",
    )?;
    let first = collect_case(source.path()).await?;
    std::fs::create_dir(source.path().join("chapters"))?;
    std::fs::rename(
        source.path().join("index.md"),
        source.path().join("chapters/start.md"),
    )?;
    let second = collect_case(source.path()).await?;
    async fn identities(dataset: &Dataset) -> Result<Vec<String>> {
        let mut rows = dataset.select("SELECT DISTINCT ?subject WHERE { VALUES ?kind { <https://ekgf.org/ontology/grapharch#Topic> <https://ekgf.org/ontology/grapharch#Example> } GRAPH ?graph { ?subject a ?kind } } ORDER BY ?subject".into()).await?;
        let mut ids = Vec::new();
        while let Some(row) = rows.next().await? {
            ids.push(row["subject"].to_string());
        }
        Ok(ids)
    }
    assert_eq!(
        identities(&first.dataset).await?.len(),
        3,
        "whitespace before the first heading must not create an empty topic"
    );
    assert_eq!(
        identities(&first.dataset).await?,
        identities(&second.dataset).await?
    );
    Ok(())
}

#[tokio::test]
async fn invalid_site_generations_preserve_the_previous_complete_site()
-> Result<()> {
    let source = tempfile::tempdir()?;
    let output = tempfile::tempdir()?;
    setup(source.path(), "Valid initial content.")?;
    let first = collect_case(source.path()).await?;
    Publisher::new(first.dataset)
        .render(&first.plan, output.path())
        .await?;
    let original = std::fs::read(output.path().join("site/index.html"))?;
    for body in [
        "[Missing](missing.md)",
        "[Missing heading](#absent)",
        "<script>alert(1)</script>",
    ] {
        setup(source.path(), body)?;
        let broken = collect_case(source.path()).await?;
        assert!(
            Publisher::new(broken.dataset)
                .render(&broken.plan, output.path())
                .await
                .is_err()
        );
        assert_eq!(
            std::fs::read(output.path().join("site/index.html"))?,
            original
        );
    }
    setup(source.path(), "Valid again.")?;
    std::fs::write(
        source.path().join("other.md"),
        "---\ntitle: Other\npermalink: /\n---\nOther",
    )?;
    let duplicate = collect_case(source.path()).await?;
    let error = Publisher::new(duplicate.dataset)
        .render(&duplicate.plan, output.path())
        .await
        .err()
        .unwrap();
    assert!(
        error.to_string().contains("duplicate website route"),
        "{error:#}"
    );
    assert_eq!(
        std::fs::read(output.path().join("site/index.html"))?,
        original
    );
    Ok(())
}

#[tokio::test]
async fn website_ownership_rejects_unowned_nested_files() -> Result<()> {
    let source = tempfile::tempdir()?;
    let output = tempfile::tempdir()?;
    setup(source.path(), "Initial")?;
    std::fs::write(
        source.path().join("child.md"),
        "---\ntitle: Child\n---\n# Child",
    )?;
    let built = collect_case(source.path()).await?;
    let publisher = Publisher::new(built.dataset);
    publisher.render(&built.plan, output.path()).await?;
    let foreign = output.path().join("site/child/foreign.txt");
    std::fs::write(&foreign, "owned by someone else")?;
    let error = publisher
        .render(&built.plan, output.path())
        .await
        .err()
        .unwrap();
    assert!(
        error.to_string().contains("unowned artifact"),
        "{error:#}"
    );
    assert_eq!(
        std::fs::read_to_string(foreign)?,
        "owned by someone else"
    );
    Ok(())
}

#[tokio::test]
async fn callouts_render_labels_without_leaking_markers_or_changing_regular_quotes()
-> Result<()> {
    let source = tempfile::tempdir()?;
    let output = tempfile::tempdir()?;
    let mut body = String::new();
    for kind in ["NOTE", "TIP", "IMPORTANT", "WARNING", "CAUTION"] {
        body.push_str(&format!("> [!{kind}]\n> Keep **formatted text** and [links](https://example.org).\n>\n> A second paragraph.\n\n"));
    }
    body.push_str(
        "> Ordinary quotation.\n\nAn inline marker [!NOTE] stays \
         literal.\n\n```text\n> [!WARNING]\n```\n",
    );
    setup(source.path(), &body)?;
    let built = collect_case(source.path()).await?;
    let PublishOutcome::Published(publication) = Publisher::new(built.dataset)
        .render(&built.plan, output.path())
        .await?
    else {
        panic!("expected publication")
    };
    let html =
        std::fs::read_to_string(publication.directory.join("index.html"))?;
    let document = scraper::Html::parse_document(&html);
    for kind in ["note", "tip", "important", "warning", "caution"] {
        let selector = scraper::Selector::parse(&format!(
            "blockquote.markdown-alert-{kind}"
        ))
        .unwrap();
        let callout = document
            .select(&selector)
            .next()
            .unwrap_or_else(|| panic!("missing {kind} callout"));
        let text = callout.text().collect::<String>();
        assert!(!text.contains("[!"), "marker leaked: {text}");
        let label = scraper::Selector::parse(".callout-title").unwrap();
        assert_eq!(
            callout
                .select(&label)
                .next()
                .unwrap()
                .text()
                .collect::<String>()
                .to_lowercase(),
            kind
        );
        assert!(
            callout
                .inner_html()
                .contains("<strong>formatted text</strong>")
        );
        assert!(text.contains("A second paragraph."));
    }
    assert!(html.contains("<blockquote>\n<p>Ordinary quotation.</p>"));
    assert!(html.contains("An inline marker [!NOTE] stays literal."));
    assert!(html.contains("&gt; [!WARNING]"));
    Ok(())
}

#[tokio::test]
async fn gfm_task_lists_preserve_completion_states_and_mixed_nested_list_semantics()
-> Result<()> {
    let source = tempfile::tempdir()?;
    let output = tempfile::tempdir()?;
    setup(
        source.path(),
        "- [ ] Pending **work**\n- [x] Completed work\n  - [ ] Nested task\n- \
         Ordinary bullet\n\n1. [x] Ordered task\n2. Ordinary numbered \
         item\n\n~~Removed text~~\n\n| Column | Value |\n| --- | --- |\n| One \
         | Two |",
    )?;
    let built = collect_case(source.path()).await?;
    let PublishOutcome::Published(publication) = Publisher::new(built.dataset)
        .render(&built.plan, output.path())
        .await?
    else {
        panic!("expected publication")
    };
    let html =
        std::fs::read_to_string(publication.directory.join("index.html"))?;
    let document = scraper::Html::parse_document(&html);
    let tasks = scraper::Selector::parse("li.task-list-item").unwrap();
    assert_eq!(document.select(&tasks).count(), 4);
    let checked = scraper::Selector::parse(
        "li.task-list-item > input[type=checkbox][checked][disabled]",
    )
    .unwrap();
    assert_eq!(document.select(&checked).count(), 2);
    let unchecked = scraper::Selector::parse(
        "li.task-list-item > input[type=checkbox][disabled]:not([checked])",
    )
    .unwrap();
    assert_eq!(document.select(&unchecked).count(), 2);
    assert!(html.contains("<li>Ordinary bullet</li>"));
    assert!(html.contains("<li>Ordinary numbered item</li>"));
    assert!(html.contains("<del>Removed text</del>"));
    assert!(html.contains("<table>"));
    Ok(())
}

