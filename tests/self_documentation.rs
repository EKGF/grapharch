#[tokio::test]
async fn generation_credit_is_in_the_footer_not_the_navigation() -> Result<()> {
    let source = tempfile::tempdir()?;
    setup(source.path(), "Welcome to the documentation.")?;
    let built = collect_case(source.path()).await?;
    let output = tempfile::tempdir()?;
    let PublishOutcome::Published(publication) = Publisher::new(built.dataset)
        .render(&built.plan, output.path())
        .await?
    else {
        panic!("publication required")
    };
    let html =
        std::fs::read_to_string(publication.directory.join("index.html"))?;
    let document = scraper::Html::parse_document(&html);
    let navigation = document
        .select(&scraper::Selector::parse(".site-navigation").unwrap())
        .next()
        .unwrap();
    assert!(
        !navigation
            .text()
            .collect::<String>()
            .contains("Generated by Grapharch"),
        "navigation should contain navigation, not generation credit"
    );
    let footer = document
        .select(&scraper::Selector::parse("main footer").unwrap())
        .next()
        .unwrap();
    assert_eq!(
        footer
            .text()
            .collect::<String>()
            .split('·')
            .next()
            .unwrap()
            .trim(),
        format!(
            "Generated by Grapharch {}",
            env!("CARGO_PKG_VERSION")
        )
    );
    let credit = footer
        .select(
            &scraper::Selector::parse(
                "a[href='https://ekgf.github.io/grapharch/']",
            )
            .unwrap(),
        )
        .next()
        .expect("versioned generator credit must link to Grapharch");
    assert_eq!(
        credit.text().collect::<String>(),
        format!("Grapharch {}", env!("CARGO_PKG_VERSION"))
    );
    assert_eq!(html.matches("Generated by ").count(), 1);
    Ok(())
}
