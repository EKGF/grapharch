#[tokio::test]
async fn grapharch_documents_itself_from_an_exported_kg_without_source_files()
-> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let sources = tempfile::tempdir()?;
    let docs = sources.path().join("docs");
    copy_documentation(&root.join("docs"), &docs)?;
    copy_documentation(
        &root.join("examples"),
        &sources.path().join("examples"),
    )?;
    let built = recorded_images::collect_site(
        &docs,
        &docs.join("grapharch.ttl"),
        "urn:grapharch:docs",
        "urn:grapharch:docs:website",
        4,
    )
    .await?;
    std::fs::remove_dir_all(sources.path())?;
    let mut constructs = built.dataset.select("SELECT ?kind (COUNT(DISTINCT ?subject) AS ?count) WHERE { VALUES ?kind { <https://ekgf.org/ontology/grapharch#Topic> <https://ekgf.org/ontology/grapharch#Example> } GRAPH ?graph { ?subject a ?kind } } GROUP BY ?kind".into()).await?;
    let mut kinds = 0;
    while constructs.next().await?.is_some() {
        kinds += 1;
    }
    assert_eq!(
        kinds, 2,
        "topics and code examples must be queryable constructs"
    );
    let mut example_fragments = built
        .dataset
        .select(
            "PREFIX ga: <https://ekgf.org/ontology/grapharch#> SELECT \
             ?example ?fragment WHERE { GRAPH ?graph { ?example a ga:Example \
             ; ga:fragment ?fragment . ?fragment a ga:Fragment ; ga:body \
             ?body ; ga:subject ?example } } LIMIT 1"
                .into(),
        )
        .await?;
    assert!(
        example_fragments.next().await?.is_some(),
        "code examples must be reusable documentation fragments"
    );
    let temp = tempfile::tempdir()?;
    let export = temp.path().join("documentation.nq");
    built.dataset.export(export.clone()).await?;
    let restored = Dataset::memory()?;
    restored.import(export).await?;
    let PublishOutcome::Published(publication) = Publisher::new(restored)
        .render(&built.plan, &temp.path().join("output"))
        .await?
    else {
        panic!("expected self-documentation publication")
    };
    let site = &publication.directory;
    let home = tokio::fs::read_to_string(site.join("index.html")).await?;
    assert!(home.contains(
        "Generated by <a href=\"https://ekgf.github.io/grapharch/\">Grapharch"
    ));
    assert!(home.contains("aria-label=\"Documentation\""));
    assert!(home.contains("features/targets/"));
    let document = scraper::Html::parse_document(&home);
    let branches =
        scraper::Selector::parse(".site-navigation nav details").unwrap();
    let identities: std::collections::HashSet<_> = document
        .select(&branches)
        .map(|branch| {
            branch
                .value()
                .attr("data-id")
                .expect("navigation branches require graph identities")
        })
        .collect();
    assert!(identities.contains("urn:grapharch:docs:topic:usage"));
    assert!(identities.contains("urn:grapharch:docs:topic:other"));
    assert_eq!(
        identities.len(),
        document.select(&branches).count()
    );
    let sidebar = document
        .select(&scraper::Selector::parse(".site-navigation").unwrap())
        .next()
        .unwrap();
    assert_eq!(
        sidebar.value().attr("data-project"),
        Some("urn:grapharch:docs")
    );
    assert_eq!(
        sidebar.value().attr("data-target"),
        Some("urn:grapharch:docs:website")
    );
    let scripts: Vec<_> = document
        .select(&scraper::Selector::parse("script").unwrap())
        .collect();
    assert_eq!(
        scripts.len(),
        1,
        "only renderer navigation code may execute"
    );
    assert_eq!(scripts[0].value().attrs().count(), 0);
    assert_eq!(
        scripts[0].text().collect::<String>().trim(),
        include_str!("../src/publication/render/website/nav.js")
            .replace("\r\n", "\n")
            .replace('\r', "\n")
            .trim()
    );

    let guide = tokio::fs::read_to_string(
        site.join("usage/publication-pipeline/index.html"),
    )
    .await?;
    assert!(guide.contains("grapharch-revision"));
    assert!(!guide.contains("href=\"../other/ontology/publication.ttl\""));
    assert!(site.join("other/ontology/publication.ttl").exists());
    assert!(publication.manifest.files.len() > 50);
    assert!(publication.manifest.diagnostics.is_empty());
    Ok(())
}

fn copy_documentation(source: &Path, destination: &Path) -> Result<()> {
    std::fs::create_dir_all(destination)?;
    for entry in std::fs::read_dir(source)? {
        let entry = entry?;
        let name = entry.file_name();
        if name.to_string_lossy().starts_with(['.', '_']) {
            continue;
        }
        if entry.file_type()?.is_dir() {
            copy_documentation(&entry.path(), &destination.join(name))?;
        } else {
            std::fs::copy(entry.path(), destination.join(name))?;
        }
    }
    Ok(())
}

fn setup(source: &Path, home: &str) -> Result<()> {
    std::fs::write(
        source.join("grapharch.ttl"),
        definitions_fixture::edit_definitions(
            include_str!("../docs/grapharch.ttl"),
            &["ontologySource", "showcasesSource"],
            None,
        )?,
    )?;
    std::fs::write(
        source.join("index.md"),
        format!(
            "---\ntitle: Home\npermalink: /\ngrapharch:\n  subject: \
             urn:topic:home\n---\n\n# Home\n\n{home}\n"
        ),
    )?;
    Ok(())
}

