async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.family-navigation > summary').click();
  await page.waitForFunction(()=>document.querySelector('[data-family-tree] .toc-toggle')!==null);
  await page.getByRole('button',{name:'Collapse all',exact:true}).click();
  assert(await page.locator('.toc-toggle[aria-expanded=false]').count()>0,'branches did not collapse');
  const branch=page.locator('.toc-toggle').first();
  await branch.focus(); await page.keyboard.press('Enter');
  assert(await branch.getAttribute('aria-expanded')==='true','keyboard toggle failed');
  await page.getByRole('button',{name:'Expand all',exact:true}).click();
  assert(await page.locator('.toc-toggle[aria-expanded=false]').count()===0,'expand all failed');
  await page.keyboard.press('Control+k');
  assert(await page.locator('#spec-search').isVisible(),'keyboard search failed');
  assert(await page.locator('#spec-search-query').evaluate(e=>e===document.activeElement),'search did not receive focus');
  await page.locator('#spec-search-query').fill('Parties Ontology');
  await page.locator('#spec-search-kind').selectOption('ontology');
  await page.waitForFunction(()=>document.querySelector('#spec-search-results li')!==null);
  const result=page.locator('#spec-search-results a').filter({hasText:/^Parties Ontology$/}).first();
  assert(await result.count()===1,'family-wide ontology search missing');
  await result.click();
  await page.waitForLoadState('domcontentloaded');
  assert(await page.locator('main h1').textContent()==='Parties Ontology','result opened wrong page');
  assert(await page.locator('a.pdf-download').count()===0,'HTML target has a dead PDF download');
  await page.keyboard.press('Control+k');
  await page.locator('#spec-search-kind').selectOption('module');
  await page.locator('#spec-search-query').fill('foundations');
  await page.waitForFunction(()=>document.querySelector('#spec-search-results li')!==null);
  assert((await page.locator('#spec-search-results').textContent()).toLowerCase().includes('foundations'),'module filter failed');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!document.getElementById('spec-search').open);
  assert(!(await page.locator('#spec-search').isVisible()),'Escape did not close search');
  await page.screenshot({path:'output/playwright/specification-pages-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
  await page.getByRole('button',{name:/Search & filter/}).click();
  assert(await page.locator('#spec-search').isVisible(),'mobile search failed');
  assert(await page.locator('#spec-search').evaluate(e=>e.getBoundingClientRect().right<=innerWidth),'mobile dialog overflow');
  await page.screenshot({path:'output/playwright/specification-pages-mobile.png'});
  await page.keyboard.press('Escape');
  return {collapse:true,keyboard:true,globalSearch:true,filters:true,mobile:true};
}
