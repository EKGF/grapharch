async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.reload();
  const handle = page.getByRole('separator', { name: 'Resize table of contents' });
  const width = () => page.locator('#toc').evaluate(node => node.getBoundingClientRect().width);
  check(await handle.isVisible(), 'Desktop resize handle is missing');
  await handle.dblclick();
  const initial = await width();
  const bounds = await handle.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, 240);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width / 2 + 120, 240, { steps: 8 });
  await page.mouse.up();
  check(await width() === initial + 120, 'Dragging did not resize the sidebar');
  const padding = await page.locator('body').evaluate(node => parseFloat(getComputedStyle(node).paddingLeft));
  check(padding === await width() + 32, 'Document did not move with sidebar');
  await handle.press('ArrowRight');
  const selected = await width();
  check(selected === initial + 136, 'Keyboard resizing did not work');
  await page.reload();
  check(await width() === selected, 'Width did not survive reload');
  await handle.press('End');
  check(await width() === 720, 'Maximum width is incorrect');
  await page.setViewportSize({ width: 1200, height: 900 });
  check(await width() === 640, 'Sidebar did not respect available document space');
  await page.setViewportSize({ width: 1440, height: 900 });
  await handle.press('Home');
  check(await width() === 240, 'Minimum width is incorrect');
  await handle.dblclick();
  check(await width() === initial, 'Double-click did not reset width');
  await page.setViewportSize({ width: 390, height: 844 });
  check(!(await handle.isVisible()), 'Mobile resize handle must be hidden');
  check(await page.locator('#toc').evaluate(node => getComputedStyle(node).position) === 'static', 'Mobile contents must stay in document flow');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.emulateMedia({ media: 'print' });
  check(!(await handle.isVisible()), 'Print output must hide resize handle');
  await page.emulateMedia({ media: 'screen' });
  return { drag: true, keyboard: true, persistence: true, bounds: true, reset: true, mobile: true, print: true };
}
