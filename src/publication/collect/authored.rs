use {
    super::{Collector, source::FileInput},
    crate::publication::writer::ContributionStream,
    anyhow::{Context, Result, bail, ensure},
    async_trait::async_trait,
    oxrdf::NamedNode,
    serde::Deserialize,
    std::{collections::BTreeMap, path::PathBuf, sync::Arc},
};

/// A Markdown-file collector supporting frontmatter and plain Markdown bodies.
pub struct MarkdownFile(
    FileInput,
    Option<PathBuf>,
    Option<(String, String)>,
    // Git-supplied Markdown provides its own repository-aware references.
    bool,
    // Quick-start builds derive absent titles from headings or filenames.
    bool,
    Vec<PathBuf>,
    Option<Arc<BTreeMap<String, NamedNode>>>,
);
/// A SPARQL-file collector that documents statements without executing them.
pub struct SparqlFile(FileInput);

#[derive(Default, Deserialize)]
struct Frontmatter {
    title:         Option<String>,
    description:   Option<String>,
    letter_prefix: Option<String>,
    #[serde(default)]
    grapharch:     Hints,
    #[serde(flatten)]
    page:          super::page::PageHints,
}

#[derive(Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct Hints {
    subject:           Option<String>,
    hero:              Option<String>,
    fragment:          Option<String>,
    #[serde(default)]
    fragments:         BTreeMap<String, String>,
    #[serde(default)]
    showcase_gallery:  bool,
    #[serde(default)]
    panel_sections:    Vec<String>,
    #[serde(default)]
    feature_sections:  Vec<String>,
    #[serde(default)]
    resource_sections: Vec<String>,
    #[serde(default)]
    card_icons:        BTreeMap<String, CardIcon>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct CardIcon {
    name: String,
    tone: String,
}

pub(crate) struct GeneratedPage<'a> {
    pub source:   &'a str,
    pub id:       &'a NamedNode,
    pub path:     &'a str,
    pub title:    &'a str,
    pub route:    &'a str,
    pub body:     String,
    pub revision: String,
}

impl MarkdownFile {
    /// Materialize generated Markdown without touching an original source file.
    pub(crate) fn generated(
        project: &str,
        processor: &str,
        page: GeneratedPage<'_>,
    ) -> Result<Self> {
        let input = FileInput::supplied(
            project,
            processor,
            PathBuf::from(page.path),
            page.source.into(),
            page.id.clone(),
            page.body,
            page.revision,
        )?;
        Ok(Self::supplied(
            input,
            true,
            Some((page.title.into(), page.route.into())),
        ))
    }

    pub(super) fn supplied(
        input: FileInput,
        website: bool,
        hints: Option<(String, String)>,
    ) -> Self {
        Self(
            input,
            website.then(PathBuf::new),
            hints,
            false,
            false,
            Vec::new(),
            None,
        )
    }

    /// Configure one collector instance and source file.
    pub fn new(project: &str, collector: &str, path: PathBuf) -> Result<Self> {
        Ok(Self(
            FileInput::new(project, collector, path)?,
            None,
            None,
            true,
            false,
            Vec::new(),
            None,
        ))
    }

    /// Collect page navigation and route hints relative to a documentation
    /// root.
    pub fn in_site(
        project: &str,
        collector: &str,
        root: PathBuf,
        path: PathBuf,
    ) -> Result<Self> {
        super::page::source_path(&root, &path)?;
        Ok(Self(
            FileInput::new(project, collector, path)?,
            Some(root),
            None,
            true,
            false,
            Vec::new(),
            None,
        ))
    }

    /// Bind source image paths to assets generated by configured collectors.
    pub fn with_image_bindings(
        mut self,
        bindings: Arc<BTreeMap<String, NamedNode>>,
    ) -> Self {
        self.6 = Some(bindings);
        self
    }

    /// Authorize additional roots for local Markdown includes.
    pub fn with_include_roots(mut self, roots: Vec<PathBuf>) -> Result<Self> {
        ensure!(
            roots.len() <= 8,
            "at most eight additional include roots are supported"
        );
        self.5 = roots;
        Ok(self)
    }

    pub(crate) fn with_default_title(mut self) -> Self {
        self.4 = true;
        self
    }

    /// Stable identity of the authored fragment.
    pub fn fragment_id(&self) -> NamedNode { self.0.fragment_id() }
}

impl SparqlFile {
    /// Configure one statement source.
    pub fn new(project: &str, collector: &str, path: PathBuf) -> Result<Self> {
        Ok(Self(FileInput::new(project, collector, path)?))
    }

    /// Stable identity of the statement fragment.
    pub fn fragment_id(&self) -> NamedNode { self.0.fragment_id() }
}

#[async_trait]
impl Collector for MarkdownFile {
    fn identity(&self) -> Result<super::SourceIdentity<'_>> {
        self.0.identity()
    }

    async fn produce(&self, stream: &mut ContributionStream) -> Result<String> {
        let (source, mut revision) = self.0.authored().await?;
        let normalized = source.replace("\r\n", "\n");
        let (mut frontmatter, body) =
            if let Some(rest) = normalized.strip_prefix("---\n") {
                let Some(end) = rest.find("\n---\n") else {
                    bail!(
                        "{}: unterminated frontmatter",
                        self.0.path.display()
                    )
                };
                (
                    serde_yaml::from_str::<Frontmatter>(&rest[..end])
                        .context("invalid Markdown frontmatter")?,
                    &rest[end + 5..],
                )
            } else {
                (Frontmatter::default(), normalized.as_str())
            };
        let expansion = super::includes::Expansion::read(
            &self.0,
            self.1.as_deref(),
            &self.5,
            body,
            self.3,
        )
        .await?;
        let containers = super::material_blocks::normalize(&expansion.body)?;
        let semantic_images = super::semantic_images::normalize(&containers)?;
        let variants = super::image_variants::normalize(&semantic_images)?;
        let figures = super::figures::normalize(&variants)?;
        let normalized_blocks = super::badges::normalize(
            &figures,
            frontmatter.letter_prefix.as_deref(),
        )?;
        let normalized_anchors = super::anchors::normalize(&normalized_blocks)?;
        let body = normalized_anchors.as_str();
        revision = format!(
            "semantic-includes-v1:{}:{revision}",
            expansion.revision
        );
        if self.4 && frontmatter.title.is_none() {
            frontmatter.title =
                Some(super::page::default_title(body, &self.0.path));
        }
        let input = match &frontmatter.grapharch.fragment {
            Some(fragment) => {
                self.0.select_fragment(NamedNode::new(fragment)?)?
            },
            None => self.0.clone(),
        };
        let fragments = super::markdown_structure::fragment_hints(
            &frontmatter.grapharch.fragments,
            &input.fragment_id(),
        )?;
        if let Some((title, route)) = &self.2 {
            ensure!(
                frontmatter
                    .title
                    .as_ref()
                    .is_none_or(|value| value == title),
                "conflicting Markdown title hints"
            );
            if let Some(value) = &frontmatter.page.permalink {
                ensure!(
                    super::page::route(input.source()?, Some(value))? ==
                        super::page::route(input.source()?, Some(route))?,
                    "conflicting Markdown route hints"
                );
            }
            frontmatter.title = Some(title.clone());
            frontmatter.page.permalink = Some(route.clone());
        }
        let mut subject = frontmatter
            .grapharch
            .subject
            .map(NamedNode::new)
            .transpose()?;
        let mut metadata = expansion.metadata;
        if self.1.is_some() || !fragments.is_empty() {
            let page = subject.clone().unwrap_or_else(|| input.fragment_id());
            metadata.extend(super::markdown_structure::describe(
                &input, &page, body, &fragments,
            )?);
        }
        if let Some(root) = &self.1 {
            use oxrdf::Literal;
            let fragment =
                subject.clone().unwrap_or_else(|| input.fragment_id());
            let source = super::page::source_path(root, &input.path)?;
            ensure!(
                frontmatter.page.aliases.len() <= 64,
                "page exceeds 64 route aliases"
            );
            for alias in &frontmatter.page.aliases {
                ensure!(
                    alias.len() <= 2048,
                    "route alias exceeds 2048 bytes"
                );
                let route = super::page::route("index.md", Some(alias))?;
                metadata.push(input.quad(
                    &fragment,
                    "routeAlias",
                    Literal::new_simple_literal(route),
                ));
            }

            revision = format!("site-page-v8:{source}:{revision}");
            subject = Some(fragment.clone());
            metadata.push(input.quad(
                &input.fragment_id(),
                "partOf",
                fragment.clone(),
            ));
            if let Some(title) = &frontmatter.title {
                metadata.push(oxrdf::Quad::new(
                    fragment.clone(),
                    NamedNode::new_unchecked("http://purl.org/dc/terms/title"),
                    Literal::new_simple_literal(title),
                    oxrdf::GraphName::DefaultGraph,
                ));
            }
            if let Some(description) = &frontmatter.description {
                anyhow::ensure!(
                    !description.trim().is_empty() && description.len() <= 2048,
                    "page description must contain 1–2048 bytes"
                );
                metadata.push(oxrdf::Quad::new(
                    fragment.clone(),
                    NamedNode::new_unchecked(
                        "http://purl.org/dc/terms/description",
                    ),
                    Literal::new_simple_literal(description),
                    oxrdf::GraphName::DefaultGraph,
                ));
            }
            if let Some(hero) = &frontmatter.grapharch.hero {
                metadata.push(input.quad(
                    &fragment,
                    "heroKind",
                    Literal::new_simple_literal(hero),
                ));
            }
            ensure!(
                frontmatter.grapharch.panel_sections.len() <= 32,
                "page exceeds 32 panel sections"
            );
            for anchor in &frontmatter.grapharch.panel_sections {
                metadata.push(input.quad(
                    &fragment,
                    "panelSection",
                    Literal::new_simple_literal(anchor),
                ));
            }
            ensure!(
                frontmatter.grapharch.feature_sections.len() <= 32,
                "page exceeds 32 feature sections"
            );
            for anchor in &frontmatter.grapharch.feature_sections {
                metadata.push(input.quad(
                    &fragment,
                    "featureSection",
                    Literal::new_simple_literal(anchor),
                ));
            }
            ensure!(
                frontmatter.grapharch.resource_sections.len() <= 32,
                "page exceeds 32 resource sections"
            );
            for anchor in &frontmatter.grapharch.resource_sections {
                metadata.push(input.quad(
                    &fragment,
                    "resourceSection",
                    Literal::new_simple_literal(anchor),
                ));
            }
            ensure!(
                frontmatter.grapharch.card_icons.len() <= 128,
                "page exceeds 128 card icons"
            );
            for (anchor, icon) in &frontmatter.grapharch.card_icons {
                let binding = crate::publication::dataset::identity(
                    "card-presentation",
                    &[fragment.as_str(), anchor],
                );
                metadata.push(input.quad(
                    &fragment,
                    "cardPresentation",
                    binding.clone(),
                ));
                for (predicate, value) in [
                    ("headingAnchor", anchor.as_str()),
                    ("iconName", icon.name.as_str()),
                    ("iconTone", icon.tone.as_str()),
                ] {
                    metadata.push(input.quad(
                        &binding,
                        predicate,
                        Literal::new_simple_literal(value),
                    ));
                }
            }
            if frontmatter.grapharch.showcase_gallery {
                metadata.push(input.quad(
                    &fragment,
                    "showcaseGallery",
                    Literal::from(true),
                ));
            }
            metadata.extend([
                input.quad(
                    &fragment,
                    "type",
                    crate::publication::term("Page"),
                ),
                input.quad(
                    &fragment,
                    "sourcePath",
                    Literal::new_simple_literal(&source),
                ),
                input.quad(
                    &fragment,
                    "route",
                    Literal::new_simple_literal(super::page::route(
                        &source,
                        frontmatter.page.permalink.as_deref(),
                    )?),
                ),
                input.quad(
                    &fragment,
                    "navigationOrder",
                    Literal::from(frontmatter.page.nav_order.unwrap_or(999)),
                ),
                input.quad(
                    &fragment,
                    "navigationHidden",
                    Literal::from(frontmatter.page.nav_exclude),
                ),
            ]);
            if let Some(parent) = &frontmatter.page.parent {
                metadata.push(input.quad(
                    &fragment,
                    "parentTitle",
                    Literal::new_simple_literal(parent),
                ));
            }
            ensure!(
                frontmatter.title.is_some(),
                "{}: website pages require a frontmatter title",
                source
            );
        }
        if self.3 {
            let images = super::markdown_images::describe(
                &input,
                self.1.as_deref(),
                body,
                self.6.as_deref(),
            )
            .await?;
            if !images.is_empty() {
                revision = format!("markdown-http-images-v1:{revision}");
            }
            metadata.extend(images);
        }
        let mut quads = input.description(
            body,
            "text/markdown",
            subject,
            frontmatter.title.as_deref(),
            &revision,
        )?;
        quads.extend(metadata);
        for quad in quads {
            stream.write(quad).await?;
        }
        Ok(revision)
    }
}

#[async_trait]
impl Collector for SparqlFile {
    fn identity(&self) -> Result<super::SourceIdentity<'_>> {
        self.0.identity()
    }

    async fn produce(&self, stream: &mut ContributionStream) -> Result<String> {
        let (source, revision) = self.0.authored().await?;
        let mut subject = None;
        for line in source.lines() {
            if let Some(pragma) = line.trim().strip_prefix("# grapharch:") {
                let Some(value) = pragma.strip_prefix("subject ") else {
                    bail!("unsupported SPARQL documentation pragma: {pragma}")
                };
                ensure!(
                    subject.is_none(),
                    "conflicting SPARQL subject pragmas"
                );
                subject = Some(NamedNode::new(value.trim())?);
            }
        }
        let quads = self.0.description(
            &source,
            "application/sparql-query",
            subject,
            None,
            &revision,
        )?;
        stream.push(quads).await?;
        Ok(revision)
    }
}
