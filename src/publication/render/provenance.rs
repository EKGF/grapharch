//! Human-readable generation evidence, read only from the pinned source graph.
mod read;
use {
    super::{
        markup::{html_escape, quote, structural_heading},
        model::Plan,
    },
    anyhow::Result,
    tokio::io::{AsyncWrite, AsyncWriteExt},
};

pub(super) const ID: &str = "document-provenance";

#[derive(Default)]
pub(super) struct Provenance {
    // bounded: at most 128 source repositories, five commits and 64 tags each.
    repositories: Vec<Repository>,
    // bounded: at most sixteen explicitly recorded build operators.
    operators:    Vec<String>,
}
struct Repository {
    url:          String,
    commit:       String,
    working_tree: bool,
    tags:         Vec<String>,
    releases:     Vec<(String, String)>,
    commits:      Vec<Commit>,
}
struct Commit {
    id:        String,
    committer: String,
    time:      String,
}

impl Provenance {
    pub(super) async fn read(plan: &Plan) -> Result<Self> {
        read::read(plan).await
    }

    pub(super) async fn html(
        &self,
        file: &mut (impl AsyncWrite + Unpin),
        title: &str,
    ) -> Result<()> {
        file.write_all(
            format!(
                "<section id=\"{ID}\" class=\"document-provenance\">{}<p>This \
                 record identifies the generator and the source revisions \
                 collected for this publication. Committers below describe \
                 recent repository changes, rather than authorship of the \
                 whole document.</p><dl><dt>Generated \
                 by</dt><dd>{}</dd><dt>Build operator</dt><dd>{}</dd></dl>",
                structural_heading(2, title, ID),
                super::credit::HTML.strip_prefix("Generated by ").unwrap(),
                html_escape(&self.operator())
            )
            .as_bytes(),
        )
        .await?;
        if self.repositories.is_empty() {
            file.write_all(b"<p>No Git repository revision was recorded for these sources.</p>").await?;
        }
        for repo in &self.repositories {
            file.write_all(
                format!(
                    "<div class=\"provenance-source\"><h3>Source \
                     repository</h3><dl><dt>Repository</dt><dd><a \
                     href=\"{}\">{}</a></dd><dt>Source \
                     commit</dt><dd><code>{}</code></dd><dt>Source \
                     state</dt><dd>{}</dd>",
                    html_escape(&repo.url),
                    html_escape(&repo.url),
                    html_escape(&repo.commit),
                    state(repo.working_tree)
                )
                .as_bytes(),
            )
            .await?;
            if !repo.tags.is_empty() {
                file.write_all(
                    format!(
                        "<dt>Git tags at this commit</dt><dd>{}</dd>",
                        html_escape(&repo.tags.join(", "))
                    )
                    .as_bytes(),
                )
                .await?;
            }
            for (label, url) in &repo.releases {
                file.write_all(
                    format!(
                        "<dt>Recorded release</dt><dd><a \
                         href=\"{}\">{}</a></dd>",
                        html_escape(url),
                        html_escape(label)
                    )
                    .as_bytes(),
                )
                .await?;
            }
            file.write_all(b"</dl><h4>Recent committers</h4><p>Up to five commits, following the first-parent history from the source commit. This is not the full contributor list.</p><ol class=\"provenance-commits\">").await?;
            for commit in &repo.commits {
                file.write_all(
                    format!(
                        "<li><strong>{}</strong> \
                         <time>{}</time><br><code>{}</code></li>",
                        html_escape(&commit.committer),
                        html_escape(&commit.time),
                        html_escape(&commit.id)
                    )
                    .as_bytes(),
                )
                .await?;
            }
            file.write_all(b"</ol></div>").await?;
        }
        file.write_all(b"</section>").await?;
        Ok(())
    }

    pub(super) async fn typst(
        &self,
        file: &mut (impl AsyncWrite + Unpin),
        preceding_appendices: Option<u32>,
    ) -> Result<()> {
        file.write_all(b"#pagebreak()\n#[\n").await?;
        if let Some(count) = preceding_appendices {
            file.write_all(
                format!(
                    "#set heading(numbering: \
                     \"A.1\")\n#counter(heading).update({count})\n#\
                     heading(level: 1)[Document provenance]\n"
                )
                .as_bytes(),
            )
            .await?;
        } else {
            file.write_all(
                b"#heading(level: 1, numbering: none)[Document provenance]\n",
            )
            .await?;
        }
        text(
            file,
            "This record identifies the generator and source revisions \
             collected for this publication. Recent committers describe \
             repository changes, rather than authorship of the whole document.",
        )
        .await?;
        field(
            file,
            "Generated by",
            &format!("Grapharch {}", env!("CARGO_PKG_VERSION")),
        )
        .await?;
        field(file, "Build operator", &self.operator()).await?;
        if self.repositories.is_empty() {
            text(
                file,
                "No Git repository revision was recorded for these sources.",
            )
            .await?;
        }
        for repo in &self.repositories {
            file.write_all(
                b"#heading(level: 2, numbering: none)[Source repository]\n",
            )
            .await?;
            field(file, "Repository", &repo.url).await?;
            field(file, "Source commit", &repo.commit).await?;
            field(file, "Source state", state(repo.working_tree)).await?;
            if !repo.tags.is_empty() {
                field(
                    file,
                    "Git tags at this commit",
                    &repo.tags.join(", "),
                )
                .await?;
            }
            for (name, url) in &repo.releases {
                field(
                    file,
                    "Recorded release",
                    &format!("{name} ({url})"),
                )
                .await?;
            }
            file.write_all(
                b"#heading(level: 3, numbering: none)[Recent committers]\n",
            )
            .await?;
            text(
                file,
                "Up to five commits, following the first-parent history from \
                 the source commit. This is not the full contributor list.",
            )
            .await?;
            for commit in &repo.commits {
                file.write_all(
                    format!(
                        "#block(above: 7pt, breakable: \
                         false)[#strong[#text({})] \
                         #text({})#linebreak()#text(size: 8pt, {})]\n",
                        quote(&commit.committer),
                        quote(&commit.time),
                        quote(&commit.id)
                    )
                    .as_bytes(),
                )
                .await?;
            }
        }
        file.write_all(b"]\n").await?;
        Ok(())
    }

    fn operator(&self) -> String {
        if self.operators.is_empty() {
            "Build operator was not recorded.".into()
        } else {
            self.operators.join(", ")
        }
    }
}
fn state(working: bool) -> &'static str {
    if working {
        "Local working tree observed against this commit; collected files may \
         contain uncommitted changes."
    } else {
        "Committed source tree pinned to this exact revision."
    }
}
async fn text(file: &mut (impl AsyncWrite + Unpin), value: &str) -> Result<()> {
    file.write_all(
        format!("#block(above: 7pt)[#text({})]\n", quote(value)).as_bytes(),
    )
    .await?;
    Ok(())
}
async fn field(
    file: &mut (impl AsyncWrite + Unpin),
    label: &str,
    value: &str,
) -> Result<()> {
    file.write_all(
        format!(
            "#block(above: 6pt)[#strong[#text({})]#linebreak()#text({})]\n",
            quote(label),
            quote(value)
        )
        .as_bytes(),
    )
    .await?;
    Ok(())
}
